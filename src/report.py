"""PDF report generation with reportlab."""
from __future__ import annotations

import io

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from .learning import learning_note

NAVY, TEAL, AMBER = colors.HexColor("#0F2C4C"), colors.HexColor("#0D9488"), colors.HexColor("#F59E0B")


def _esc(s: str) -> str:
    return str(s).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def build_pdf(result, ats: dict, bullets: list[dict], cv_name: str = "CV", jd_name: str = "Job description") -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm, bottomMargin=16 * mm,
                            title="Resume and Job Match Report")
    ss = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=ss["Title"], textColor=NAVY, fontSize=20)
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], textColor=TEAL)
    body = ss["BodyText"]
    el = [Paragraph("Resume and Job Match Report", h1),
          Paragraph(f"CV: {_esc(cv_name)} &nbsp;&nbsp; Job: {_esc(jd_name)}", body), Spacer(1, 6),
          Paragraph(f"<b>Overall match: {result.overall:.0f}/100 ({result.verdict})</b> &nbsp;&nbsp; ATS readiness: {ats['score']}/100", body)]

    def table(rows, widths=None, header=True):
        t = Table(rows, colWidths=widths, repeatRows=1 if header else 0)
        st = [("GRID", (0, 0), (-1, -1), 0.4, colors.lightgrey), ("VALIGN", (0, 0), (-1, -1), "TOP"),
              ("FONTSIZE", (0, 0), (-1, -1), 8.5)]
        if header:
            st += [("BACKGROUND", (0, 0), (-1, 0), NAVY), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white)]
        t.setStyle(TableStyle(st))
        return t

    P = lambda s: Paragraph(_esc(s), body)
    el += [Paragraph("Score breakdown", h2),
           table([["Component", "Score", "Weight"]] + [[k.title(), f"{v:.0f}", f"{w:.0%}"] for (k, v), w in
                  zip(result.components.items(), [0.35, 0.25, 0.15, 0.15, 0.10])], [60 * mm, 30 * mm, 30 * mm])]
    el += [Paragraph("Skills", h2), table([
        ["Matched required", P(", ".join(result.matched_required) or "None")],
        ["Missing required", P(", ".join(result.missing_required) or "None")],
        ["Matched preferred", P(", ".join(result.matched_preferred) or "None")],
        ["Missing preferred", P(", ".join(result.missing_preferred) or "None")],
        ["Missing keywords", P(", ".join(result.keywords_missing) or "None")]], [40 * mm, 134 * mm], header=False)]
    el += [Paragraph("Experience and education", h2), table([
        ["CV experience", f"{result.cv_years:g} years ({result.cv_seniority})"],
        ["Job requirement", f"{result.jd_years:g}+ years" if result.jd_years else "Not stated"],
        ["Job seniority", result.jd_seniority], ["Seniority fit", result.seniority_fit],
        ["Education", f"CV: {result.cv_education}; job: {result.jd_education}"]], [40 * mm, 134 * mm], header=False)]
    el += [Paragraph("Improvement suggestions", h2)] + [Paragraph("- " + _esc(s), body) for s in result.suggestions]
    gaps = result.missing_required + result.missing_preferred
    if gaps:
        el += [Paragraph("Skill-gap learning plan", h2),
               table([["Skill", "What to learn"]] + [[g, P(learning_note(g))] for g in gaps], [40 * mm, 134 * mm])]
    el += [Paragraph("ATS compatibility", h2)]
    el += [table([["Severity", "Issue"]] + [[i["severity"], P(i["issue"])] for i in ats["issues"]], [25 * mm, 149 * mm])] if ats["issues"] else [P("No ATS issues detected.")]
    if bullets:
        el += [Paragraph("Bullet-point improvements", h2),
               table([["Original", "Suggested rewrite"]] + [[P(b["original"]), P(b["suggested_rewrite"])] for b in bullets[:12]], [87 * mm, 87 * mm])]
    el += [Spacer(1, 8), Paragraph("Generated by Resume and Job Matcher. Scores are decision support, not a hiring decision.", ss["Italic"])]
    doc.build(el)
    return buf.getvalue()
